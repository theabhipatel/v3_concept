// Copies the voice activity detection (VAD) files from node_modules into public/vad/, so live
// conversation loads them from this site instead of a CDN. Runs on install, dev and build.
//
// The folder name carries both package versions (public/vad/<vad>-<ort>/), so files can be
// cached for a year: an upgrade gets a new URL instead of a stale cached file. It also writes
// components/abi/vad-assets.ts with that path for live.ts and the background prefetch.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const version = (pkg) => JSON.parse(readFileSync(join(web, "node_modules", pkg, "package.json"), "utf8")).version;

const VAD = "@ricky0123/vad-web";
const ORT = "onnxruntime-web";
if (!existsSync(join(web, "node_modules", VAD))) {
  console.log("[vad] package not installed yet, skipping");
  process.exit(0);
}

// Only what live conversation actually loads (checked in the browser's network log).
const FILES = [
  [VAD, "dist/silero_vad_v5.onnx"],
  [VAD, "dist/vad.worklet.bundle.min.js"],
  [ORT, "dist/ort-wasm-simd-threaded.mjs"],
  [ORT, "dist/ort-wasm-simd-threaded.wasm"],
];

const folder = `${version(VAD)}-${version(ORT)}`;
const root = join(web, "public", "vad");
const out = join(root, folder);
mkdirSync(out, { recursive: true });

// Remove folders from older versions.
for (const name of readdirSync(root)) if (name !== folder) rmSync(join(root, name), { recursive: true, force: true });

for (const [pkg, file] of FILES) cpSync(join(web, "node_modules", pkg, file), join(out, file.split("/").pop()));

const path = `/vad/${folder}/`;
const ts = `// Generated by scripts/copy-vad-assets.mjs. Do not edit by hand.
/** Where the self-hosted VAD files live (versioned, cached for a year). */
export const VAD_ASSET_PATH = "${path}";
/** The files live conversation loads, warmed in the background on page load. */
export const VAD_PREFETCH = ${JSON.stringify(["silero_vad_v5.onnx", "ort-wasm-simd-threaded.mjs", "ort-wasm-simd-threaded.wasm"].map((f) => path + f))};
`;
const target = join(web, "components", "abi", "vad-assets.ts");
if (!existsSync(target) || readFileSync(target, "utf8") !== ts) writeFileSync(target, ts);
console.log(`[vad] copied ${FILES.length} files to public${path}`);
